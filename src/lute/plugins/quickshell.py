import lute.config as config
from lute.theme import ThemeNode
from lute.plugins.base import Plugin
import subprocess
from rich import print
import json5 as json

class QuickshellPlugin(Plugin):
    """ Plugin for Quickshell toolkit. """
    dislpay_name = "QuickShell"
    name = "quickshell"
    version = "0.0.1"

    def detect(self) -> bool:
        """ Detects whether the app is installed """
        if subprocess.run("which qs > /dev/null 2>&1", shell=True, ).returncode == 0:
            return True
        return False

    def is_plugged_in(self) -> bool:
        """ Detects if the app is plugged in """
        path = config.xdg_config_home() / "quickshell"
        # 1. make sure that quickshell/Lute is on PATH
          #  will do later
        # 2. make sure that at least one config in qs/*/shell.qml imports Lute module
        if not path.is_dir():
            return False
        for file in path.iterdir():
            file = file / "shell.qml"
            if not file.is_file():
                continue
            with file.open(encoding="utf-8") as qs_conf:
                for line in qs_conf:
                    if line.strip() == "import Lute":
                        return True
        return False

    def generate_variables(self, theme: Theme) -> None:
        """ Generates the lute variables in the app's supported format, to be 
        imported at the TOP of a config and used as variables """
        # generate every file in quickshell/Lute/... with the required contents
        # Lute/qmldir
        qmldir_path = config.xdg_config_home()/"quickshell"/"Lute"/"qmldir"
        with qmldir_path.open("w", encoding="utf-8") as qmldir:
            qmldir.write("""module Lute
singleton Lute 1.0 Lute.qml""")
        #Lute/Lute.qml
        def recursive_dict_conversion(value):
            if isinstance(value, ThemeNode):
                return {
                    name: recursive_dict_conversion(child)
                    for name, child in vars(value).items()
                }

            if isinstance(value, dict):
                return {
                    name: recursive_dict_conversion(child)
                    for name, child in value.items()
                }

            if isinstance(value, list):
                return [recursive_dict_conversion(child) for child in value]

            return value
        theme = recursive_dict_conversion(theme)
        theme_data = recursive_dict_conversion(theme)

        properties = []
        for name, value in theme_data.items():
            serialized = json.dumps(value, indent=4, ensure_ascii=False)
            properties.append(f"    readonly property var {name}: ({serialized})")
        values = "\n".join(properties)

        luteqml_path = config.xdg_config_home()/"quickshell"/"Lute"/"Lute.qml"
        with luteqml_path.open("w", encoding="utf-8") as lgf:
            lgf.write(
f""" // AUTO-GENERATED BY LUTE
// use these values in any file that "import"s Lute
pragma Singleton

import QtQml
import Quickshell
import Quickshell.Io

QtObject {{
    // VALUES SHOULD BE HERE... 
    {values}
    // IPC Refresh Handler (do not touch)
    property IpcHandler refreshHandler: IpcHandler {{
        target: "lute"

        function refresh(): void {{
            Quickshell.reload(false)
        }}
    }}
}}
""")
    def generate_overrides(self, theme: Theme) -> None:
        """ Generates lute theme-based overrides to import at the BOTTOM of a
        config """
        print("ez mode is not supported for quickshell yet!")
        raise NotImplementedError

    def refresh(self, quiet=True) -> None:
        """ Refresh the app to apply the config. Should NEVER close and reopen
        the app, this is only intended for a dynamic reloading """
        loaded_configs = subprocess.run("qs list --all" +
                                        "| awk -F 'Config path: ' '{print $2}'" +
                                        "| awk -F '/quickshell/' '{print $2}'" +
                                        "| awk -F '/shell.qml' '{print $1}'",
                        shell=True, 
                        capture_output=True, 
                        text=True, 
                        check=True).stdout.splitlines()
        for config in loaded_configs:
            if quiet:
                subprocess.run("qs -c {config} ipc call lute refresh > /dev/null 2>&1", shell=True)
            else:
                subprocess.run("qs -c {config} ipc call lute refresh", shell=True)

    def help_install(self) -> None:
        """ Display help messages to guide the user to installing the plugin
        for the app """ 
        print("[default]This is the hardest install: you have to make sure that quickshell/Lute is on path AND that at least one config in quickshell/*/shell.qml imports Lute")
