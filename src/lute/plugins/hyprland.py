import lute.config as config
from lute.plugins.base import Plugin
import subprocess
from rich import print

class HyprlandPlugin(Plugin):
    """ Plugin for Hyprland WL compositor """
    display_name = "Hyprland"
    name = "hyprland"
    version = "0.0.1"

    def detect(self) -> bool:
        """ Detects whether the app is installed """
        if subprocess.run("which hyprland > /dev/null 2>&1", shell=True, ).returncode == 0:
            return True
        return False

    def is_plugged_in(self) -> bool:
        """ Detects if the app is plugged in """
        path = config.xdg_config_home() / "hypr" / "hyprland.lua"
        with path.open(encoding="utf-8") as hypr_conf:
            for line in hypr_conf:
                if line.strip() in ["require('lute-generated')",
                                    'require("lute-generated")']:
                    return True
        return False

    def generate_variables(self, theme: Theme) -> None:
        """ Generates the lute variables in the app's supported format, to be
        imported at the TOP of a config and used as variables """
        path = config.xdg_config_home() / "hypr" / "lute-generated.lua"
        with path.open("w", encoding="utf-8") as lgf:
            geo = theme.geometry
            # calculation of the 'roudning' field.
            rounding = False if geo.corner_shape == "sharp" else sum(geo.corner_radius)//4
            # rounding power calculation for corner shapes
            rounding_power = 1
            if geo.corner_shape == "beveled":
                roudning_power = 1
            else:
                rounding_power = 2


            # for lists lua uses '{}' instead of '[]' so you have to do
            # str(value).strip('[]') for every list...       so cool!
            lgf.write(
f"""-- AUTO-GENERATED BY LUTE
-- use these values in any config file that's "require()"d by hyprland.lua (recursively)
-- colors
-- corners
lute_rounding = {rounding}

-- borders
lute_rounding_power = {rounding_power}
lute_border_size = {geo.border_width}

--gaps
lute_gaps_in = {{{str(geo.gaps.inner).strip("[]")}}}
lute_gaps_out = {{{str(geo.gaps.outer).strip("[]")}}}
"""
)

    def generate_overrides(self, theme: Theme) -> None:
        """ Generates lute theme-based overrides to import at the BOTTOM of a
        config """
        raise NotImplementedError

    def refresh(self, quiet=True) -> None:
        """ Refresh the app to apply the config. Should NEVER close and reopen
        the app, this is only intended for a dynamic reloading """
        if quiet:
            subprocess.run("hyprctl reload > /dev/null 2>&1", shell=True)
        else:
            subprocess.run("hyprctl reload", shell=True)

    def help_install(self, ez_mode=False) -> None:
        """ Display help messages to guide the user to installing the plugin
        for the app """ 
        if ez_mode:
            print("ez mode is not supported yet!")
        else:
            print(r"""[default][yellow]NOTE[/]: To plug in hyprland you need to add [yellow]'require(lute-generated.lua)'[/] to the top of your hyprland.lua. Any other files [yellow]require()[/]'d afterwards will have access to lute variables from this file.""")
